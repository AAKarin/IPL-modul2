public class Tugas1 {
    public static void main(String[] args) {
        int divisor = 0;
        int dividend = 3;

        if (divisor == 0) {
            System.out.println("Error: Division by zero is not allowed.");
        } else {
            System.out.println(dividend / divisor);
        }
    }
}
